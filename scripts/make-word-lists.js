#!/usr/bin/env node
// Word Ladder and Word Hunt word lists. Run: node scripts/make-word-lists.js
//
// Sources, in app/src/main/assets/words (all derived from the app's own SCOWL-based lists):
//   answers.txt    the common words (Word Race secret words)
//   grid.txt       the Letter Grid words (more 6 letter words for the ladder)
//   blocklist.txt  words kept out of both new games (written by hand, one per line)
//   hunt.txt       Word Hunt themes written by hand: "Name|WORD WORD ..."
// Writes:
//   ladder.txt     the common 4, 5 and 6 letter words, UPPERCASE, minus the blocklist
//   backend/cloudflare/src/wordgamelists.js   the same data for the server (tests check they match)
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../app/src/main/assets/words/', import.meta.url);
const read = (name) => readFileSync(new URL(name, dir), 'utf8').split('\n').map((s) => s.trim()).filter(Boolean);

const blocked = new Set(read('blocklist.txt'));
// 4 and 5 letters: the common words only. The common 6 letter words are too few to join up (the
// biggest group is 10 words), so 6 letter words from the Letter Grid list (grid.txt) join them.
const common = read('answers.txt').filter((w) => w.length >= 4 && w.length <= 6);
const more = read('grid.txt').filter((w) => w.length === 6);
const ladder = [...new Set([...common, ...more])]
  .map((w) => w.toUpperCase())
  .filter((w) => !blocked.has(w))
  .sort((a, b) => a.length - b.length || (a < b ? -1 : 1));
const themes = read('hunt.txt').map((line) => {
  const [name, words] = line.split('|');
  const list = words.split(' ').filter(Boolean);
  const bad = list.filter((w) => blocked.has(w));
  if (bad.length) throw new Error(`${name} has blocked words: ${bad}`);
  return [name, list];
});

writeFileSync(new URL('ladder.txt', dir), ladder.join('\n') + '\n');
const out = `// Word Ladder and Word Hunt word lists, generated by scripts/make-word-lists.js from
// app/src/main/assets/words/{ladder,blocklist,hunt}.txt (a test checks they match). UPPERCASE.
// From SCOWL by Kevin Atkinson; see app/src/main/assets/words/SCOWL-Copyright.txt.

export const LADDER = '${ladder.join(' ')}';

export const BLOCKLIST = '${[...blocked].join(' ')}';

export const HUNT_THEMES = {
${themes.map(([n, l]) => `  ${n}: '${l.join(' ')}',`).join('\n')}
};
`;
writeFileSync(new URL('../../../../../backend/cloudflare/src/wordgamelists.js', dir), out);
console.log(`ladder ${ladder.length}, themes ${themes.map(([n, l]) => `${n} ${l.length}`).join(', ')}`);
