#!/usr/bin/env python3
"""Turns the sticker drawings in scripts/art/*.svg into Kotlin the app can draw.

Each sticker is a hand-drawn SVG on a 120x120 grid: a backdrop, then plain shapes (path, rect,
circle, ellipse, polygon) with flat fills and strokes. This writes their shapes, in order, to
app/src/main/java/com/pippop/ui/art/StickerArt.kt; the backdrop and frame are drawn there by hand.

    python3 scripts/make-stickers.py
"""

import os
import re
import xml.etree.ElementTree as ET

HERE = os.path.dirname(__file__)
OUT = os.path.join(HERE, '..', 'app', 'src', 'main', 'java', 'com', 'pippop', 'ui', 'art', 'StickerArt.kt')
STICKERS = {'KYLIAN': 'kylian-dictador.svg'}
NS = '{http://www.w3.org/2000/svg}'


def num(v):
    return f'{float(v):g}'


def as_path(el):
    """The element's outline as SVG path data."""
    tag = el.tag.replace(NS, '')
    a = el.attrib
    if tag == 'path':
        return re.sub(r'\s+', ' ', a['d']).strip()
    if tag == 'rect':
        x, y, w, h = (float(a.get(k, 0)) for k in ('x', 'y', 'width', 'height'))
        return f'M{num(x)} {num(y)} h{num(w)} v{num(h)} h{num(-w)} Z'
    if tag in ('circle', 'ellipse'):
        cx, cy = float(a['cx']), float(a['cy'])
        rx = float(a.get('r', a.get('rx')))
        ry = float(a.get('r', a.get('ry')))
        return (f'M{num(cx - rx)} {num(cy)} a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0 '
                f'a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0 Z')
    if tag == 'polygon':
        pts = a['points'].split()
        return 'M' + ' L'.join(p.replace(',', ' ') for p in pts) + ' Z'
    raise ValueError(f'{tag} is not supported')


def colour(value, opacity):
    """0xAARRGGBB, or null for none. SVG's default fill is black."""
    if value == 'none':
        return 'null'
    value = value or '#000'
    if len(value) == 4:
        value = '#' + ''.join(c * 2 for c in value[1:])
    alpha = round(float(opacity) * 255)
    return f'0x{alpha:02X}{value[1:].upper()}L'


def parts(svg):
    root = ET.parse(os.path.join(HERE, 'art', svg)).getroot()
    framed = next(g for g in root.iter(NS + 'g') if 'clip-path' in g.attrib)
    shapes = [el for el in framed if el.tag.replace(NS, '') != 'defs'][1:]  # skip the backdrop
    out = []
    for el in shapes:
        a = el.attrib
        if 'transform' in a:
            raise ValueError('transforms are not supported: bake them into the shape')
        fill = colour(a.get('fill'), a.get('fill-opacity', 1))
        stroke = colour(a.get('stroke', 'none'), a.get('stroke-opacity', 1))
        width = num(a.get('stroke-width', 1))
        dash = a.get('stroke-dasharray')
        dash = 'floatArrayOf(' + ', '.join(f'{float(d)}f' for d in dash.split()) + ')' if dash else 'null'
        cap = a.get('stroke-linecap') == 'round'
        join = a.get('stroke-linejoin') == 'round'
        out.append(f'        Part("{as_path(el)}", {fill}, {stroke}, {width}f, {dash}, {str(cap).lower()}, {str(join).lower()}),')
    return out


def main():
    lines = [
        '// Generated by scripts/make-stickers.py from scripts/art/*.svg. Change the drawing there, not here.',
        'package com.pippop.ui.art',
        '',
        'internal object StickerArt {',
    ]
    for name, svg in STICKERS.items():
        lines.append(f'    /** From scripts/art/{svg}. */')
        lines.append(f'    val {name} = listOf(')
        lines += parts(svg)
        lines.append('    )')
    lines.append('}')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(OUT)


if __name__ == '__main__':
    main()
